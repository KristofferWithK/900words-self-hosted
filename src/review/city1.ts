export function recordingUrl(row: BoardSentence, recordings: readonly SentenceRecording[], variant: SentenceVariant = 'normal'): string | undefined {
  return recordings.find(r => r.audioId === row.audioId && r.sentenceId === row.sentenceId &&
    r.version === row.version && r.textDa === row.text.da && r.variant === variant && r.bakeRate === SENTENCE_BAKE_RATES[variant] && r.playbackRate === 1 &&
    // A row's clip lives under its own language's directory: da:mor under /audio/da/city1/.
    r.url.startsWith(`/audio/${row.wordId.slice(0, 2)}/city1/`) && !r.url.includes('..'))?.url
}
export type QueuePin = Pick<ReviewSentence, 'wordId' | 'targetId' | 'sentenceId' | 'audioId' | 'version'> & {
  clueHistoryIndex: number; clueText: string; clueNumber: number
}
export interface QueueState { version: 1; roundId: string; queue: QueuePin[]; cursor: number; dismissed: boolean }
const rowKeys = ['wordId', 'targetId', 'sentenceId', 'audioId', 'version'] as const
const validClue = (c: Clue | undefined): c is Clue => !!c && c.by === 'player' &&
  typeof c.text === 'string' && c.text.trim().length > 0 && c.text === c.text.trim() &&
  Number.isInteger(c.number) && c.number >= 1 && c.number <= MAX_CLUE_NUMBER && Array.isArray(c.guesses)
const copyPin = (p: QueuePin): QueuePin => ({ wordId: p.wordId, targetId: p.targetId,
  sentenceId: p.sentenceId, audioId: p.audioId, version: p.version,
  clueHistoryIndex: p.clueHistoryIndex, clueText: p.clueText, clueNumber: p.clueNumber })
export const dismissedQueue = (roundId: string): QueueState => ({ version: 1, roundId, queue: [], cursor: 0, dismissed: true })

export function selectQueue(history: readonly Clue[], rows: readonly ReviewSentence[], usedTargetIds: readonly string[] = []): QueuePin[] {
  const byWord = new Map(rows.map(r => [r.wordId, r]))
  const used = new Set(usedTargetIds), queue: QueuePin[] = []
  for (const [clueHistoryIndex, clue] of history.entries()) {
    if (!validClue(clue)) continue
    const candidates = clue.guesses.filter(g => g?.result === 'green').map(g => byWord.get(g.wordId)).filter((r): r is ReviewSentence => !!r)
    const row = candidates.find(r => !used.has(r.targetId)) ?? candidates[0]
    if (!row) continue
    queue.push(copyPin({ ...row, clueHistoryIndex, clueText: clue.text, clueNumber: clue.number }))
    used.add(row.targetId)
  }
  return queue
}
export function restoreQueue(saved: unknown, roundId: string, rows: readonly ReviewSentence[], history: readonly Clue[]): QueueState {
  const dismissed = dismissedQueue(roundId)
  if (!saved || typeof saved !== 'object') return dismissed
  const s = saved as QueueState
  if (s.version !== 1 || s.roundId !== roundId || s.dismissed !== false || !Array.isArray(history) ||
    !Array.isArray(s.queue) || !Number.isInteger(s.cursor) || s.cursor < 0 || s.cursor >= s.queue.length) return dismissed
  let previous = -1
  for (const pin of s.queue) {
    if (!pin || !Number.isInteger(pin.clueHistoryIndex) || pin.clueHistoryIndex <= previous) return dismissed
    const clue = history[pin.clueHistoryIndex]
    if (!validClue(clue) || pin.clueText !== clue.text || pin.clueNumber !== clue.number ||
      !clue.guesses.some(g => g?.wordId === pin.wordId && g?.result === 'green') ||
      !rows.some(r => rowKeys.every(k => r[k] === pin[k]))) return dismissed
    previous = pin.clueHistoryIndex
  }
  return { version: 1, roundId, queue: s.queue.map(copyPin), cursor: s.cursor, dismissed: false }
}
export function nextSentence(state: QueueState): QueueState {
  if (state.dismissed) return state
  const cursor = state.cursor + 1
  return cursor >= state.queue.length ? { ...state, dismissed: true } : { ...state, cursor }
}
export function resolveSentence(pin: QueuePin, rows: readonly ReviewSentence[]) {
  return rows.find(r => rowKeys.every(k => r[k] === pin[k]))
}

/** Resolve the exact row the review surface can render, not merely its cursor. */
export function currentReviewSentence(
  state: QueueState | null,
  rows: readonly ReviewSentence[],
): { pin: QueuePin; row: ReviewSentence } | null {
  if (!state || state.dismissed || !Number.isInteger(state.cursor) || state.cursor < 0) return null
  const pin = state.queue[state.cursor]
  if (!pin) return null
  const row = resolveSentence(pin, rows)
  return row ? { pin, row } : null
}

/** The next control is offered only when its saved pin resolves as well. */
export function nextReviewSentenceAvailable(
  state: QueueState | null,
  rows: readonly ReviewSentence[],
): boolean {
  if (!state || state.dismissed || !currentReviewSentence(state, rows)) return false
  const nextPin = state.queue[state.cursor + 1]
  return !!nextPin && !!resolveSentence(nextPin, rows)
}
