// Port of the authoring contract. Only acceptance-validated successor content
// belongs here; editorial evidence is checked at import, never invented at runtime.
export interface Span { text: string; start: number; end: number }
export interface Pair { da: string; en: string }
export interface Stage { city: 0; use: 'productive-target' | 'controlled-target' | 'preview-as-chunk' | 'receptive-ambient' }
export interface Accepted { version: number; status: 'accepted'; approval: { artifact: string; sha256: string } }
export interface BoardSentence extends Accepted {
  wordId: string; city: 0; sourceSha256: string; sentenceId: string; audioId: string
  text: Pair; wordSpan: Span
}
export interface ReviewSentence extends BoardSentence {
  targetId: string; targetStage: Stage; targetSpan: Span
}
export interface AboutTarget extends Accepted {
  targetId: string; targetStage: Stage; meaningEn: string; usageEn: string
  example: Pair; targetSpan: Span
}
export interface Envelope<T, K extends string> {
  version: 1; base: string; language: 'da'; city: 0; kind: K; rows: readonly T[]
}
export type SentenceVariant = 'normal' | 'slow'
export const SENTENCE_BAKE_RATES = { normal: 1, slow: 0.7 } as const
export interface SentenceRecording {
  audioId: string; sentenceId: string; version: number; textDa: string
  url: string; variant: SentenceVariant; bakeRate: 1 | 0.7; playbackRate: 1
}
export interface City1Catalog {
  board: readonly BoardSentence[]
  review: readonly ReviewSentence[]
  about: readonly AboutTarget[]
  recordings: readonly SentenceRecording[]
}
