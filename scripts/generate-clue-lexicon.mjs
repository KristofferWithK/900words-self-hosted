/**
 * L1's client-safe slice of Casey's authored clue books.
 *
 * The books are deliberately private Worker modules: each association carries
 * its target membership, score, vote, and rationale. The dictionary needs none
 * of that. This generator takes only the Danish and English strings from every
 * available book, chooses one stable pair per normalized Danish term, and
 * writes the small lazy client asset.
 *
 * It also takes the clue words of the authored City 1 bank
 * (authored-clues.da.<city>.json, Casey's pre-verified clues per board), clue
 * and English gloss only. Those are the clues Casey actually gives at launch,
 * and 174 of them were in no book: «forrige» on bank_001 went to the model
 * as if it were English, because the Danish course's translate prompt only
 * translates INTO Danish (owner play note, 2026-09-27). The board, the targets
 * and the grouping never leave the Worker; a bare clue word says nothing about
 * any key.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const BOOK_DIR = join(ROOT, 'proxy', 'data')
export const OUTPUT_PATH = join(ROOT, 'src', 'data', 'clue-lexicon.da.json')
const WORDS_PATH = join(ROOT, 'src', 'data', 'words.da.json')
const BOOK_FILE = /^book\.da\.(\d+)\.json$/
const BANK_FILE = /^authored-clues\.da\.(\d+)\.json$/

const normalize = (value) => value.normalize('NFC').trim().toLowerCase()
const compare = (left, right) => (left < right ? -1 : left > right ? 1 : 0)

/** Every available city book, in a filesystem- and locale-independent order. */
export function bookPaths(directory = BOOK_DIR) {
  return readdirSync(directory)
    .map((name) => ({ name, match: BOOK_FILE.exec(name) }))
    .filter((entry) => entry.match)
    .sort((left, right) => Number(left.match[1]) - Number(right.match[1]) || compare(left.name, right.name))
    .map(({ name }) => join(directory, name))
}

export function readBooks(directory = BOOK_DIR) {
  const paths = bookPaths(directory)
  if (paths.length === 0) throw new Error(`no Danish clue books found in ${directory}`)
  return paths.map((path) => ({ path, book: JSON.parse(readFileSync(path, 'utf8')) }))
}

/**
 * Every authored bank in the same shape `authoredTerms` reads: a Danish "book"
 * whose only section holds the bank's clue words as {da, en}. The flattening
 * happens here, so nothing but the two strings reaches the transform.
 */
export function readBanks(directory = BOOK_DIR) {
  return readdirSync(directory)
    .map((name) => ({ name, match: BANK_FILE.exec(name) }))
    .filter((entry) => entry.match)
    .sort((left, right) => Number(left.match[1]) - Number(right.match[1]) || compare(left.name, right.name))
    .map(({ name }) => {
      const path = join(directory, name)
      const bank = JSON.parse(readFileSync(path, 'utf8'))
      if (!Array.isArray(bank?.boards)) throw new Error(`${path}: not an authored clue bank`)
      const assoc = bank.boards.flatMap((board) =>
        (board.caseyClueGroups ?? []).map((group) => ({ da: group.clue, en: group.clueEnglish })),
      )
      return { path, book: { lang: 'da', words: { bank: { assoc } } } }
    })
}

/** The books first, then the banks: ties resolve by the strings, not by order. */
export function allSources(directory = BOOK_DIR) {
  return [...readBooks(directory), ...readBanks(directory)]
}

const taughtDanish = () => {
  const words = JSON.parse(readFileSync(WORDS_PATH, 'utf8'))
  return new Set(words.map((word) => normalize(word.da)))
}

/**
 * The deliberately narrow transform. Individual word associations and the
 * values in pair associations are authored clue terms; their target ids, pair
 * keys/membership, and metadata never enter the result. Ties are resolved by
 * the two public strings, so a book's incidental object order can never alter
 * a generated byte.
 */
export function authoredTerms(sources) {
  const unique = new Map()
  for (const { path, book } of sources) {
    if (book?.lang !== 'da' || !book.words || typeof book.words !== 'object') {
      throw new Error(`${path}: not a Danish clue book`)
    }
    // `pairs` are also authored clue terms. Their *keys* and membership are
    // private, so this flattens their values into the same anonymous term list
    // as ordinary associations before any client data is written.
    const sections = [
      ...Object.keys(book.words)
        .sort(compare)
        .map((wordId) => ({ at: wordId, entries: book.words[wordId]?.assoc })),
      ...Object.keys(book.pairs ?? {})
        .sort(compare)
        .map((pair) => ({ at: pair, entries: book.pairs[pair] })),
    ]
    for (const { at, entries } of sections) {
      if (!Array.isArray(entries)) throw new Error(`${path}: ${at} has no association list`)
      for (const association of entries) {
        if (typeof association?.da !== 'string' || typeof association?.en !== 'string') {
          throw new Error(`${path}: ${at} has an association without Danish and English text`)
        }
        const da = association.da.normalize('NFC').trim()
        const en = association.en.normalize('NFC').trim()
        const key = normalize(da)
        if (!key || !en) throw new Error(`${path}: ${at} has a blank association term`)
        const candidate = { da, en }
        const current = unique.get(key)
        if (!current || compare(candidate.da, current.da) < 0 || (candidate.da === current.da && compare(candidate.en, current.en) < 0)) {
          unique.set(key, candidate)
        }
      }
    }
  }
  return [...unique.values()].sort(
    (left, right) =>
      compare(normalize(left.da), normalize(right.da)) ||
      compare(left.da, right.da) ||
      compare(left.en, right.en),
  )
}

/**
 * The course's 900 words are already in the eager local index. Keeping them
 * out of this chunk is what makes the generated layer minimal; together the
 * two indexes still cover every unique authored clue term.
 */
export function deriveLexicon(sources = allSources(), taught = taughtDanish()) {
  return authoredTerms(sources).filter((entry) => !taught.has(normalize(entry.da)))
}

export function renderedLexicon(sources = allSources()) {
  return `${JSON.stringify(deriveLexicon(sources))}\n`
}

// Git may materialise this generated JSON with CRLF on Windows. The generator
// deliberately owns content and ordering, not a checkout's line-ending policy.
const normaliseCheckoutNewlines = (value) => value.replace(/\r\n/g, '\n')

export function measureLexicon(rendered = renderedLexicon()) {
  const bytes = Buffer.byteLength(rendered)
  return { rawBytes: bytes, gzipBytes: gzipSync(rendered, { mtime: 0 }).byteLength }
}

function main() {
  const rendered = renderedLexicon()
  const measure = measureLexicon(rendered)
  if (process.argv.includes('--check')) {
    if (!existsSync(OUTPUT_PATH) || normaliseCheckoutNewlines(readFileSync(OUTPUT_PATH, 'utf8')) !== rendered) {
      console.error(`L1 clue lexicon is stale: run node scripts/generate-clue-lexicon.mjs`)
      process.exit(1)
    }
    const terms = authoredTerms(allSources())
    console.log(
      `L1 clue lexicon: ${terms.length} authored terms (${deriveLexicon(allSources()).length} outside the taught 900), ` +
        `${measure.rawBytes} B raw, ${measure.gzipBytes} B gzip`,
    )
    return
  }
  writeFileSync(OUTPUT_PATH, rendered)
  const terms = authoredTerms(allSources())
  console.log(
    `wrote ${OUTPUT_PATH}: ${terms.length} authored terms (${deriveLexicon(allSources()).length} outside the taught 900), ` +
      `${measure.rawBytes} B raw, ${measure.gzipBytes} B gzip`,
  )
}

const invoked = process.argv[1] ? resolve(process.argv[1]) === fileURLToPath(import.meta.url) : false
if (invoked) main()
