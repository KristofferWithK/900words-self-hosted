import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function sourceValue(fileName, declarationName, bindings = {}) {
  const source = readFileSync(resolve(ROOT, fileName), 'utf8')
  const declaration = new RegExp(`(?:export\\s+)?const\\s+${declarationName}(?:\\s*:[^=]+)?\\s*=`).exec(source)
  if (!declaration) throw new Error(`${fileName} does not declare ${declarationName}`)
  const expression = balancedExpression(source, declaration.index + declaration[0].length, fileName)
  // These declarations are static data literals. Reading them this way
  // keeps the documentation tied to their exact committed source rather than a
  // hand-maintained copy.
  const names = Object.keys(bindings)
  return Function(...names, `return (${expression})`)(...names.map((name) => bindings[name]))
}

function balancedExpression(source, start, fileName) {
  let depth = 0
  let quote
  let escaped = false
  let opened = false
  for (let index = start; index < source.length; index++) {
    const char = source[index]
    if (quote) {
      if (escaped) escaped = false
      else if (char === '\\') escaped = true
      else if (char === quote) quote = undefined
      continue
    }
    if (char === "'" || char === '"' || char === '`') {
      quote = char
      continue
    }
    if (char === '{' || char === '[' || char === '(') {
      depth++
      opened = true
      continue
    }
    if (char === '}' || char === ']' || char === ')') {
      depth--
      if (opened && depth === 0) return source.slice(start, index + 1).trim()
    }
  }
  throw new Error(`${fileName} has an unclosed data literal`)
}

function acceptedCourse() {
  const lessons = sourceValue('src/lang/da/beginner-grammar-lessons.ts', 'DANISH_BEGINNER_GRAMMAR_LESSONS')
  const brief = sourceValue('src/lang/da/curriculum-grammar-brief.ts', 'DANISH_GRAMMAR_REWRITE_BRIEF', {
    DANISH_BEGINNER_GRAMMAR_LESSONS: lessons,
  })
  const cities = sourceValue('src/lang/da/route.ts', 'CITIES')
  if (brief.status !== 'accepted') throw new Error('Danish grammar brief is not accepted')
  if (!Array.isArray(brief.chapters) || brief.chapters.length !== 9) {
    throw new Error(`Danish grammar brief has ${brief.chapters?.length ?? 'no'} chapters, expected nine`)
  }
  if (!Array.isArray(cities) || cities.length !== 9) throw new Error('Danish route does not have nine cities')
  const cityNames = new Map(cities.map((city) => [city.id, city.name]))
  const mismatches = brief.chapters
    .map((chapter, index) => chapter.cityId === cities[index].id ? undefined : `${index + 1}: ${chapter.cityId}`)
    .filter(Boolean)
  if (mismatches.length > 0) throw new Error(`brief is not in route order (${mismatches.join(', ')})`)
  return { brief, cityNames }
}

export function renderGrammarDocument() {
  const { brief, cityNames } = acceptedCourse()
  const lines = [
    '# Danish train grammar',
    '',
    '> **Status: reference.** Generated course reference; validate against the accepted curriculum source.',
    '> Start with [the working guide](WORKING.md) and [current launch scope](LAUNCH.md).',
    '',
    '> **Generated canonical course.** Do not edit this file by hand. It is an exact',
    '> projection of the accepted `src/lang/da/curriculum-grammar-brief.ts`;',
    '> `npm run validate:grammar` rejects any byte drift.',
    '',
    'Each chapter belongs to the city it prepares. Sønderborg is available before',
    'the first ordinary board; the rides into Ribe through København teach chapters',
    '2–9. Every concept has one rules page followed by one examples page, and a',
    'city may own several lessons. There is no lesson after København.',
    '',
    'The app turns this accepted brief into the optional train reading. This document',
    'is the readable repository projection of that same live course.',
  ]
  for (const [index, chapter] of brief.chapters.entries()) {
    const city = cityNames.get(chapter.cityId)
    if (!city) throw new Error(`chapter ${index + 1} references an unknown city`)
    lines.push(
      '',
      `## ${index + 1} · ${city} — *${chapter.titleDa}* / ${chapter.titleEn}`,
      '',
      `**Focus.** ${chapter.formalFocusEn}`,
      '',
      '### What to notice',
      '',
      ...chapter.rewriteEn.map((point) => `- ${point}`),
      '',
      '### Examples',
      '',
      ...chapter.modelExamplesDa.map((example) => `- \`${example}\``),
      '',
      '### Keep in mind',
      '',
      ...chapter.doNotClaimEn.map((point) => `- ${point}`),
    )
    const lessons = [chapter.lesson, ...(chapter.additionalLessons ?? [])]
    for (const [lessonIndex, lesson] of lessons.entries()) {
      lines.push(
        '',
        `### Reader lesson ${lessonIndex + 1} — *${lesson.titleDa}* / ${lesson.titleEn}`,
        '',
        `#### Rules page — ${lesson.rulesContext}`,
        '',
        ...lesson.rules.map((block) => block.kind === 'table'
          ? `- ${block.rows.map((row) => row.join(' · ')).join('; ')}`
          : `- ${block.text}`),
        '',
        '#### Translated examples page',
        '',
        ...lesson.examples.map(([da, en]) => `- \`${da}\` — ${en}`),
      )
    }
  }
  return `${lines.join('\n')}\n`
}

